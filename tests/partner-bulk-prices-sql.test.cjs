const { PGlite } = require('@electric-sql/pglite');
const { btree_gist } = require('@electric-sql/pglite/contrib/btree_gist');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const schema = require('./fixtures/price-grid-schema.json');
const a = '10000000-0000-4000-8000-000000000001';
const b = '10000000-0000-4000-8000-000000000002';
const c = '10000000-0000-4000-8000-000000000003';
const band = (price = 100) => ({ minimumAge: 0, maximumAge: 65, oneYearPrice: price, twoYearPrice: price * 2, isActive: true });
(async () => {
  const db = new PGlite({ extensions: { btree_gist } });
  try {
    await db.exec('create role anon; create role authenticated; create role service_role; create table partners(id uuid primary key, company_name text, is_active boolean);');
    for (const [table, def] of Object.entries(schema)) {
      const cols = Object.entries(def.properties).map(([name, v]) => `"${name}" ${name === 'id' ? 'bigint generated by default as identity primary key' : v.format}${name === 'created_at' || name === 'updated_at' ? ' default now()' : ''}${def.required.includes(name) && name !== 'id' ? ' not null' : ''}`);
      await db.exec(`create table ${table}(${cols.join(',')});`);
    }
    for (const name of ['202609170002_price_grid_atomic.sql','20261117132643_bulk_partner_price_grid.sql']) await db.exec(fs.readFileSync(path.join(__dirname, '../supabase/migrations', name), 'utf8'));
    await db.query('insert into partners values($1,\'A\',true),($2,\'B\',false),($3,\'C\',true)', [a,b,c]);
    const snapshot = async () => (await db.query('select all_partner_price_snapshot() as data')).rows[0].data;
    const individual = async (id, ranges) => db.query('select save_price_grid($1,price_grid_snapshot($2),$2)', [JSON.stringify(ranges), id]);
    const save = async (ranges, revision) => (await db.query('select save_all_partner_price_grids($1,$2) as data', [JSON.stringify(ranges), revision])).rows[0].data;
    await individual(a, [band(110)]); await individual(b, [band(120)]);
    await db.query('select save_price_grid($1,\'[]\',null)', [JSON.stringify([band(900)])]);
    const direct = (await db.query('select price_grid_snapshot(null) as data')).rows[0].data;
    const before = await snapshot();
    const saved = await save([band(150)], before.revision);
    assert.equal(saved.updatedCount, 3);
    const after = await snapshot();
    assert.equal(saved.revision, after.revision);
    assert.notEqual(after.revision, before.revision);
    for (const partner of after.partners) { assert.equal(partner.ranges.length, 1); assert.equal(partner.ranges[0].oneYearPrice, 150); }
    assert.deepEqual((await db.query('select price_grid_snapshot(null) as data')).rows[0].data, direct);
    await assert.rejects(() => save([band(200)], before.revision), e => e.code === 'PT409');
    await individual(a, [band(175)]);
    await assert.rejects(() => save([band(200)], after.revision), e => e.code === 'PT409');
    let current = await snapshot();
    assert.equal(current.partners.find(p => p.id === a).ranges[0].oneYearPrice, 175);
    assert.equal(current.partners.find(p => p.id === b).ranges[0].oneYearPrice, 150);
    await assert.rejects(() => save([band(-5)], current.revision));
    await assert.rejects(() => save([band(),band()], current.revision), e => e.code === '23P01');
    assert.deepEqual(await snapshot(), current);
    // A failure on the second partner must roll back the already-written first grid.
    await db.exec(`create function reject_second() returns trigger language plpgsql as $$ begin if new.partner_id='${b}'::uuid and new.one_year_price=999 then raise exception 'simulated late failure'; end if; return new; end $$; create trigger late_failure before insert on partner_price_ranges for each row execute function reject_second();`);
    await assert.rejects(() => save([band(999)], current.revision), /simulated late failure/);
    assert.deepEqual(await snapshot(), current);
    await db.query('insert into partners values(\'10000000-0000-4000-8000-000000000004\',\'D\',true)');
    await assert.rejects(() => save([band(250)], current.revision), e => e.code === 'PT409');
    current = await snapshot();
    for (const role of ['anon','authenticated']) {
      await db.exec('set role ' + role);
      await assert.rejects(() => snapshot(), e => e.code === '42501');
      await assert.rejects(() => save([band()], current.revision), e => e.code === '42501');
      await db.exec('reset role');
    }
    await db.exec('grant usage on schema public to service_role; grant all on all tables in schema public to service_role; grant usage,select on all sequences in schema public to service_role; set role service_role;');
    assert.equal((await save([band(250)], current.revision)).updatedCount, 4);
    await db.exec('reset role');
    console.log('PASS: all partners (including inactive/empty), individual edits, conflicts/retries, membership changes, invalid grids, late-error rollback, direct-grid isolation, server-only grants.');
  } finally { await db.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
